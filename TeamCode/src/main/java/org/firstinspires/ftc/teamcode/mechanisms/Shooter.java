package org.firstinspires.ftc.teamcode.mechanisms;

import static com.rmsftc.utils.config.vars.kt.TypesKt.BoolVar;

import com.pedropathing.math.Velocity;
import com.qualcomm.robotcore.hardware.DcMotorEx;
import com.qualcomm.robotcore.hardware.HardwareMap;

import com.rmsftc.utils.AllianceColor;
import com.rmsftc.utils.Clock;
import org.firstinspires.ftc.teamcode.util.control.Controller;
import org.firstinspires.ftc.teamcode.util.control.DoubleFlywheelFullVelocityConstants;
import org.firstinspires.ftc.teamcode.util.game.Field;
import org.firstinspires.ftc.teamcode.util.Direction;
import org.firstinspires.ftc.teamcode.util.hardware.actuator.SmartFlywheel;
import com.rmsftc.utils.math.Pose;
import org.firstinspires.ftc.teamcode.util.shotcalc.ShotCalculator;
import org.firstinspires.ftc.teamcode.util.shotcalc.ShotContext;
import org.firstinspires.ftc.teamcode.util.shotcalc.ShotSolution;
import com.rmsftc.utils.config.vars.Var;
import org.firstinspires.ftc.teamcode.planners.Constants;

public class Shooter {
    /** Ticks/sec within which a motor counts as up to speed. */

    // Generated by the Shooter PIDSVA Tuner (Pedro AutoTune Procedure).
// Target: 2875 RPM.
// ---- main ----
// Ku=0.0272896, Tu=1.34730 s.
// SVA fit: RMSE=7.09247 V, R^2=0.334545, samples=515.
// kS/kV/kA are in volts (voltage compensation ON).
// TODO-USER-CONSTANTS: verify ticksPerRev and the shot table before use.
    DoubleFlywheelFullVelocityConstants mainConstants = new DoubleFlywheelFullVelocityConstants(
            Constants.Shooter.SmartFlywheel.Main.KP,  // kP
            Constants.Shooter.SmartFlywheel.Main.KI,  // kI
            Constants.Shooter.SmartFlywheel.Main.KD,  // kD
            Constants.Shooter.SmartFlywheel.Main.KS,  // kS
            Constants.Shooter.SmartFlywheel.Main.KV,  // kV
            Constants.Shooter.SmartFlywheel.Main.KA,  // kA
            Constants.Shooter.SmartFlywheel.Main.TOLERANCE_TICKS_PER_SEC,  // tolerance (ticks/sec)
            Constants.Shooter.SmartFlywheel.Main.INTEGRAL_LIMIT_TICKS,  // integralLimit (ticks)
            true,  // voltageCompensation
            Constants.Shooter.SmartFlywheel.Main.NOMINAL_VOLTAGE); // nominalVoltage (V)
    // ---- counter ----
// Ku=0.0448686, Tu=0.582218 s.
// SVA fit: RMSE=3.81714 V, R^2=0.647853, samples=517.
// kS/kV/kA are in volts (voltage compensation ON).
// TODO-USER-CONSTANTS: verify ticksPerRev and the shot table before use.
    DoubleFlywheelFullVelocityConstants counterConstants = new DoubleFlywheelFullVelocityConstants(
            Constants.Shooter.SmartFlywheel.Counter.KP,  // kP
            Constants.Shooter.SmartFlywheel.Counter.KI,  // kI
            Constants.Shooter.SmartFlywheel.Counter.KD,  // kD
            Constants.Shooter.SmartFlywheel.Counter.KS,  // kS
            Constants.Shooter.SmartFlywheel.Counter.KV,  // kV
            Constants.Shooter.SmartFlywheel.Counter.KA,  // kA
            Constants.Shooter.SmartFlywheel.Counter.TOLERANCE_TICKS_PER_SEC,  // tolerance (ticks/sec)
            Constants.Shooter.SmartFlywheel.Counter.INTEGRAL_LIMIT_TICKS,  // integralLimit (ticks)
            true,  // voltageCompensation
            Constants.Shooter.SmartFlywheel.Counter.NOMINAL_VOLTAGE); // nominalVoltage (V)

    public SmartFlywheel mainMotor;
    public SmartFlywheel counterRoller;

    public ShotCalculator shotCalculator;
    public AllianceColor color;
    public boolean panicking=false;
    public boolean reversing=false;
    private int target_main_velocity = 0;
    private int target_counter_velocity = 0;
    double distToGoal = 0;
    /**
     * THE single shoot-on-the-move master flag: one boolean for all of SOTM.
     * When false (default) everything behaves stationary — raw-bearing aim,
     * static table wheel speed, no pose-at-release prediction. When true, the
     * heading compensation (AutoAimerCalculator), the wheel-speed
     * compensation and the pose-at-release prediction (shot calculators) all
     * turn on together. Static so there is exactly one variable (and one FTC
     * Dashboard entry) shared by every Shooter/Robot; toggled live on the
     * dashboard — see Robot's constructor, which uploads it. Session only:
     * it resets to false on app restart.
     */
    public static final Var<Boolean> useSotm = BoolVar("Use ShootOnMove (SOTM)", false);

    public Shooter(HardwareMap hardwareMap, AllianceColor color) {
        this(hardwareMap, color, Clock.SYSTEM);
    }

    public Shooter(HardwareMap hardwareMap, AllianceColor color, Clock clock) {
        this.color = color;
        mainMotor = new SmartFlywheel(
                hardwareMap.get(DcMotorEx.class, "mainShooter"),
                Controller.doubleFlywheelFullVelocity(mainConstants, clock),
                new SmartFlywheel.Params(Constants.Shooter.SmartFlywheel.TICKS_PER_REV, 1),
                hardwareMap.voltageSensor
        );
        mainMotor.motor.setDirection(Direction.FORWARD.toMotor());
        mainMotor.motor.setZeroPowerBehavior(DcMotorEx.ZeroPowerBehavior.FLOAT);

        counterRoller = new SmartFlywheel(
                hardwareMap.get(DcMotorEx.class, "counterShooter"),
                Controller.doubleFlywheelFullVelocity(counterConstants, clock),
                new SmartFlywheel.Params(Constants.Shooter.SmartFlywheel.TICKS_PER_REV, 1),
                hardwareMap.voltageSensor
        );
        counterRoller.motor.setDirection(Direction.REVERSE.toMotor());
        counterRoller.motor.setZeroPowerBehavior(DcMotorEx.ZeroPowerBehavior.FLOAT);

        shotCalculator = ShotCalculator.table();
    }

    /** Sets velocity of both motors in ticks per second */
    public void setVelocity(int mainTicksPerSecond, int counterRollerTicksPerSecond) {
        if (mainTicksPerSecond < 0 || counterRollerTicksPerSecond < 0) {
            throw new IllegalArgumentException("Shooter velocity must be nonnegative ticks per second.");
        }
        mainMotor.setVelocity(mainTicksPerSecond);
        mainMotor.update();
        counterRoller.setVelocity(counterRollerTicksPerSecond);
        counterRoller.update();
        target_main_velocity = mainTicksPerSecond;
        target_counter_velocity = counterRollerTicksPerSecond;
        panicking = false;
        reversing = false;
    }

    public void panic() {
        mainMotor.setPower(1);
        mainMotor.update();
        counterRoller.setPower(1);
        counterRoller.update();
        panicking = true;
        reversing = false;
    }

    /**
     * Runs both outtake motors in reverse at full power to clear a ball
     * jammed against the flywheel. Hold-to-run: call setVelocity(0, 0) (via
     * Robot.endReverseOuttake) to stop. Smart shooter updates are skipped
     * while reversing, same as panicking.
     */
    public void reverseOuttake() {
        mainMotor.setPower(-1);
        mainMotor.update();
        counterRoller.setPower(-1);
        counterRoller.update();
        reversing = true;
        panicking = false;
    }

    public void solveAndSetVelocity
            (Pose robotPosition, Velocity velocity, Field.HiveState hiveState, double deltaTime)
    {
        panicking = false;
        reversing = false;
        ShotContext context = new ShotContext();
        context.robotPose = robotPosition;
        context.velocity = velocity;
        context.dt = deltaTime;
        context.hiveState = hiveState;
        context.allianceColor = color;
        context.sotm = useSotm.get();
        distToGoal = context.distanceToTarget();
        ShotSolution solution = shotCalculator.calculateShot(context);
        setVelocity((int) Math.round(solution.flywheelTicksPerSecond),
                (int) Math.round(solution.counterRollerTicksPerSecond));
    }

    public boolean upToSpeed() {
        return hasNonzeroVelocityTarget()
                && Math.abs(target_main_velocity - mainMotor.getTicksPerSecond()) <= Constants.Shooter.SmartFlywheel.UP_TO_SPEED_TOLERANCE_TICKS_PER_SEC
                && Math.abs(target_counter_velocity - counterRoller.getTicksPerSecond()) <= Constants.Shooter.SmartFlywheel.UP_TO_SPEED_TOLERANCE_TICKS_PER_SEC;
    }

    public boolean hasNonzeroVelocityTarget() {
        return target_main_velocity != 0 && target_counter_velocity != 0;
    }

    public void update() {
        mainMotor.update();
        counterRoller.update();
    }

    public String getDebugString() {
        return "Set Velocity: main=" + target_main_velocity + " counter=" + target_counter_velocity
                + "\n Get Velocity: main=" + mainMotor.getTicksPerSecond()
                + " counter=" + counterRoller.getTicksPerSecond()
                + "\n distance to goal=" + distToGoal;
    }

    public void stopImmediately() {
        target_main_velocity = 0;
        target_counter_velocity = 0;
        panicking = false;
        reversing = false;
        mainMotor.stopImmediately();
        counterRoller.stopImmediately();
    }

    public boolean panicking() {
        return panicking;
    }

    public boolean reversing() {
        return reversing;
    }
}
